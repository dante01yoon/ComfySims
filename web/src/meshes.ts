import { Mesh, Texture } from 'three'
import type { Object3D, WebGLRenderer } from 'three'
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js'

import type { Asset, Dimensions, FitMode } from '../../packages/schema/src/index.ts'
import { comfyHolding, comfyOutputFile } from './comfy.ts'
import { cachedGlb, clearGlbCache, inWorker, storeGlb } from './fit-jobs.ts'
import type { FitResult, GlbStats, Processed } from './fit-jobs.ts'

const OPTIMISER_VERSION = 1
const UPLOADS_PER_FRAME = 2

/** Where a GLB comes from and the size and fit mode it is processed for. */
export type GlbSource = { uri: string; dimensions: Dimensions; mode: FitMode }

const loader = new GLTFLoader()
const loads = new Map<string, Promise<Object3D | null>>()
const processing = new Map<string, Promise<FitResult>>()
const stats = new Map<string, GlbStats>()

/** Identifies the mesh an asset renders: a ComfyUI output is re-fitted per listed size and fit mode. */
export function meshKey({ uri, dimensions, fit }: Asset): string {
  if (!comfyOutputFile(uri)) return uri
  return `${uri}#${dimensions.width}x${dimensions.depth}x${dimensions.height}:${fit?.mode ?? 'exact'}`
}

function sourceOf(asset: Asset): GlbSource {
  return { uri: asset.uri, dimensions: asset.dimensions, mode: asset.fit?.mode ?? 'exact' }
}

function cacheKey({ uri, dimensions: { width, depth, height }, mode }: GlbSource): string {
  const fitted = comfyOutputFile(uri) ? `${mode}:align-auto` : 'unfitted'
  return `${uri}|${width}x${depth}x${height}|${fitted}|v${OPTIMISER_VERSION}`
}

async function processedBytes(key: string, { uri, dimensions, mode }: GlbSource, bytes: Uint8Array | null): Promise<FitResult> {
  if (!bytes) return { ok: false, reason: 'download' }
  const largestCm = Math.max(dimensions.width, dimensions.depth, dimensions.height)
  const result = await inWorker({ bytes, largestCm, fit: comfyOutputFile(uri) ? { dimensions, mode } : null })
  if (result.ok) {
    const { ok: _, ...value } = result
    await storeGlb(key, value)
  }
  return result
}

async function cachedOr(key: string, process: () => Promise<FitResult>): Promise<FitResult> {
  const hit = await cachedGlb(key)
  return hit ? { ok: true, ...hit } : process()
}

function remembered(key: string, pending: Promise<FitResult>): Promise<FitResult> {
  const settled = pending.then((result) => {
    if (result.ok) stats.set(key, result.stats)
    return result
  })
  processing.set(key, settled)
  return settled
}

/** A GLB optimised (and, for ComfyUI outputs, fitted) in the fit worker, once per source: from memory, the browser cache, or `download`. */
function processedGlb(source: GlbSource, download: () => Promise<Uint8Array | null>): Promise<FitResult> {
  const key = cacheKey(source)
  return processing.get(key) ?? remembered(key, cachedOr(key, async () => processedBytes(key, source, await download())))
}

/** Processes freshly generated bytes for a source, replacing what memory and the browser cache held for it. */
export function processedFresh(source: GlbSource, bytes: Uint8Array): Promise<FitResult> {
  const key = cacheKey(source)
  return remembered(key, processedBytes(key, source, bytes))
}

async function downloaded(uri: string): Promise<Uint8Array | null> {
  const file = comfyOutputFile(uri)
  if (file) {
    const outcome = await comfyHolding(uri).download(file)
    return outcome.ok ? outcome.bytes : null
  }
  const response = await fetch(uri)
  return response.ok ? new Uint8Array(await response.arrayBuffer()) : null
}

let renderer: WebGLRenderer | null = null
let rendererAttached = () => {}
const rendererReady = new Promise<void>((resolve) => {
  rendererAttached = resolve
})
const uploads: { texture: Texture; uploaded: () => void }[] = []

/** The renderer textures are uploaded to, a few per frame. */
export function attachRenderer(gl: WebGLRenderer): void {
  renderer = gl
  rendererAttached()
}

function uploadSome(): void {
  for (const { texture, uploaded } of uploads.splice(0, UPLOADS_PER_FRAME)) {
    renderer?.initTexture(texture)
    uploaded()
  }
  if (uploads.length > 0) requestAnimationFrame(uploadSome)
}

function upload(texture: Texture): Promise<void> {
  return new Promise((uploaded) => {
    uploads.push({ texture, uploaded })
    if (uploads.length === 1) requestAnimationFrame(uploadSome)
  })
}

/** Every distinct texture used by the meshes under an object. */
export function texturesIn(root: Object3D): Set<Texture> {
  const found = new Set<Texture>()
  root.traverse((object) => {
    if (!(object instanceof Mesh)) return
    for (const material of [object.material].flat()) {
      for (const value of Object.values(material)) if (value instanceof Texture) found.add(value)
    }
  })
  return found
}

async function onGpu(scene: Object3D): Promise<Object3D> {
  await rendererReady
  await Promise.all([...texturesIn(scene)].map(upload))
  return scene
}

function bufferOf(bytes: Uint8Array): ArrayBuffer {
  return new Uint8Array(bytes).buffer
}

async function parsed({ bytes }: Processed): Promise<Object3D> {
  return onGpu((await loader.parseAsync(bufferOf(bytes), '')).scene)
}

async function loadProcessed(asset: Asset): Promise<Object3D | null> {
  try {
    const result = await processedGlb(sourceOf(asset), () => downloaded(asset.uri))
    return result.ok ? await parsed(result) : null
  } catch {
    return null
  }
}

/** Loads an asset's processed mesh once per mesh key, its textures already on the GPU; resolves to null when it cannot be loaded. */
export function loadMesh(asset: Asset): Promise<Object3D | null> {
  const key = meshKey(asset)
  const cached = loads.get(key)
  if (cached) return cached
  const pending = loadProcessed(asset)
  loads.set(key, pending)
  return pending
}

/** Triangles, textures and bytes of an asset's stored GLB once it has loaded. */
export function glbStatsOf(asset: Asset): GlbStats | null {
  return stats.get(cacheKey(sourceOf(asset))) ?? null
}

/** Empties the browser cache of processed GLBs and forgets the ones in memory, so the next load downloads again. */
export async function clearAssetCache(): Promise<void> {
  loads.clear()
  processing.clear()
  stats.clear()
  await clearGlbCache()
}
