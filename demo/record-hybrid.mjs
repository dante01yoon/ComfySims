import { chromium } from '@playwright/test'
import { mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'

const OUT = 'demo/out/hybrid'
const layout = JSON.parse(readFileSync('demo/out/agent/final-state.json', 'utf8')).layout
mkdirSync(`${OUT}/video`, { recursive: true })
const started = Date.now()
const marks = []
const mark = (name, extra = {}) => { marks.push({ name, t: (Date.now() - started) / 1000, ...extra }); console.log(name, marks.at(-1).t, JSON.stringify(extra)) }
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] })
const context = await browser.newContext({ viewport: { width: 1600, height: 900 }, recordVideo: { dir: `${OUT}/video`, size: { width: 1600, height: 900 } } })
const page = await context.newPage()
await page.goto('http://127.0.0.1:5179/')
await page.waitForFunction(() => typeof window.roomfit?.ready === 'function')
await page.evaluate(() => window.roomfit.ready())
await page.evaluate((value) => window.roomfit.load(value), layout)
await page.waitForFunction(async () => (await window.roomfit.scene()).every((item) => item.meshLoaded), null, { timeout: 300_000 })
await page.evaluate(() => { window.roomfit.setView('studio'); window.roomfit.setScene('reading') })
const chip = page.getByRole('button', { name: /^(Cloud|Local) · / })
await page.evaluate(() => window.roomfit.setBackend({ kind: 'cloud' }))
await page.waitForFunction(() => window.roomfit.state().backend.status === 'ready', null, { timeout: 60_000 })
mark('ready', { chip: await chip.getAttribute('aria-label') ?? await chip.innerText() })
await page.getByRole('button', { name: 'Bedroom', exact: true }).click()
await page.waitForTimeout(2500)

await page.getByRole('button', { name: 'Render this view' }).click()
mark('cloud-render-click')
const jobs = page.getByRole('region', { name: 'Jobs' })
const renderCard = jobs.getByRole('article', { name: /^Room render/ }).first()
await renderCard.getByRole('button', { name: 'Open' }).waitFor({ timeout: 300_000 })
mark('cloud-render-done')
await page.waitForTimeout(1500)
const overlayClose = page.getByRole('button', { name: /^(Close|Back)$/ })
if (await overlayClose.first().isVisible()) { await page.waitForTimeout(2500); await overlayClose.first().click() }

await chip.click()
await page.waitForTimeout(800)
await page.getByRole('button', { name: 'Use Local' }).click()
await page.waitForFunction(() => window.roomfit.state().backend.kind === 'local' && window.roomfit.state().backend.status !== 'checking', null, { timeout: 60_000 })
mark('switched-local', { backend: await page.evaluate(() => window.roomfit.state().backend) })
await page.waitForTimeout(2500)
await chip.click()
await page.waitForTimeout(1500)
await page.getByRole('button', { name: 'Render this view' }).hover()
await page.waitForTimeout(2500)

await renderCard.getByRole('button', { name: 'View as 3D photo' }).click()
mark('local-photo3d-click')
const photoViewer = page.getByRole('dialog', { name: '3D photo' })
await photoViewer.waitFor({ timeout: 600_000 })
mark('local-photo3d-open', { job: await page.evaluate(() => window.roomfit.state().jobs.find((job) => job.kind === 'photo3d')) })
await page.waitForTimeout(1500)
const box = await photoViewer.boundingBox()
await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
await page.mouse.down()
await page.mouse.move(box.x + box.width / 2 + 500, box.y + box.height / 2 - 120, { steps: 60 })
await page.mouse.move(box.x + box.width / 2 - 400, box.y + box.height / 2 + 80, { steps: 90 })
await page.mouse.up()
await page.waitForTimeout(1000)
await photoViewer.getByRole('button', { name: 'Back' }).click()
mark('workflows')
const photoCard = jobs.getByRole('article', { name: /^3D photo/ }).first()
await photoCard.getByRole('button', { name: 'Workflow' }).click()
const panel = page.getByRole('dialog', { name: 'Workflow' })
await panel.waitFor()
await page.waitForTimeout(3500)
await panel.getByRole('button', { name: 'Close' }).click()
await renderCard.getByRole('button', { name: 'Workflow' }).click()
await panel.waitFor()
await page.waitForTimeout(3500)
await panel.getByRole('button', { name: 'Close' }).click()
await chip.click()
await page.waitForTimeout(800)
await page.getByRole('button', { name: 'Use Cloud' }).click()
await page.waitForFunction(() => window.roomfit.state().backend.kind === 'cloud' && window.roomfit.state().backend.status === 'ready', null, { timeout: 60_000 })
await page.waitForTimeout(1500)
await chip.click()
await page.waitForTimeout(2500)
mark('end', { jobs: await page.evaluate(() => window.roomfit.state().jobs.map((job) => ({ kind: job.kind, backend: job.backend, title: job.title, steps: job.steps }))) })
writeFileSync(`${OUT}/marks.json`, JSON.stringify(marks, null, 2))
const video = page.video()
await context.close()
renameSync(await video.path(), `${OUT}/raw.webm`)
await browser.close()
console.log('recorded')
